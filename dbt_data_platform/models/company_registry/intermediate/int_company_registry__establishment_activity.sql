with establishments as (
    select
        full_cnpj,
        company_root_cnpj,
        branch_order,
        check_digits,
        branch_type_code,
        trade_name,
        registration_status_code,
        registration_status_date,
        registration_status_reason_code,
        foreign_city_name,
        country_code,
        activity_start_date,
        primary_cnae_code,
        secondary_cnae_codes,
        street_type,
        street_name,
        address_number,
        address_complement,
        district,
        postal_code,
        state,
        municipality_code,
        area_code_1,
        phone_1,
        area_code_2,
        phone_2,
        fax_area_code,
        fax_number,
        email,
        special_status,
        special_status_date
    from {{ ref('stg_company_registry__establishments') }}
)

select
    full_cnpj,
    company_root_cnpj,
    branch_order,
    check_digits,
    branch_type_code,
    case when branch_type_code = '1' then true else false end as is_headquarters,
    case when branch_type_code = '2' then true else false end as is_branch,
    trade_name,
    registration_status_code,
    case when registration_status_code = '02' then true else false end as is_active,
    registration_status_date,
    registration_status_reason_code,
    foreign_city_name,
    country_code,
    activity_start_date,
    primary_cnae_code,
    secondary_cnae_codes,
    street_type,
    street_name,
    address_number,
    address_complement,
    district,
    postal_code,
    state,
    municipality_code,
    area_code_1,
    phone_1,
    area_code_2,
    phone_2,
    fax_area_code,
    fax_number,
    email,
    special_status,
    special_status_date
from establishments
